    /// <author>Almighty-Shogun</author>
    /// <since>4.0.0</since>
    public const string UserId = "userId";

    /// <summary>
    /// The claim type for granted permissions.
    /// </summary>
    /// <author>Almighty-Shogun</author>
    /// <since>4.0.0</since>
    public const string Permission = "permission";
}
